"""Writes the scene sleep:client_create (needs the Create mod): Create's moving parts in the sky for the client's
renderer - three layers of 24 driven lines (shafts, cogwheels, large cogwheels; 47 parts each, a creative motor at the
start) and 2 x 12 belts of 16 on the top layer, seen from the client scenes' view. Run from tools/:
    python gen_client_create.py > ../src/scenes/resources/data/sleep/function/client_create.mcfunction"""
out = ['# sleep:client_create - Create\'s moving parts for the client\'s renderer (needs the Create mod; ClientAuto',
       '# -Dsleep.clientAuto.scene=client_create): 3 layers x 24 driven lines of 47 shafts / cogwheels / large cogwheels and',
       '# 24 belts of 16, all turning; generated by tools/gen_client_create.py',
       'gamerule doDaylightCycle false', 'gamerule doWeatherCycle false', 'time set noon', 'weather clear',
       'fill 0 249 16 48 249 64 minecraft:smooth_stone']
kinds = ['create:shaft[axis=x]', 'create:cogwheel[axis=x]', 'create:large_cogwheel[axis=x]']
for layer, y in enumerate((250, 253, 256)):
    for i in range(24):
        z = 17 + 2 * i
        kind = kinds[(i + layer) % 3]
        if kind.startswith('create:large') and i % 2:   # large cogwheels need room: every other line only
            kind = kinds[0]
        out.append('setblock 0 %d %d create:creative_motor[facing=east]' % (y, z))
        out.append('fill 1 %d %d 47 %d %d %s' % (y, z, y, z, kind))
# belts on a layer of their own above: shafts across the ends, a motor driving the first one
for i in range(12):
    z = 17 + 4 * i
    for x0 in (2, 26):
        x1 = x0 + 15
        out.append('setblock %d 259 %d create:shaft[axis=z]' % (x0, z))
        out.append('setblock %d 259 %d create:shaft[axis=z]' % (x1, z))
        out.append('sleep createbelt %d 259 %d %d 259 %d' % (x0, z, x1, z))
        out.append('setblock %d 259 %d create:creative_motor[facing=north]' % (x0, z + 1))
print('\n'.join(out))
